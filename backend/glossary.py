import re

def explain_term(term: str) -> dict:
    """Look up a legal term in the glossary (case-insensitive)."""
    clean_term = term.lower().strip()
    
    # Exact match
    if clean_term in GLOSSARY:
        return GLOSSARY[clean_term]
    
    # Partial match
    for key, data in GLOSSARY.items():
        if key in clean_term or clean_term in key:
            return data
            
    return {
        "term": term,
        "category": "General",
        "definition": f"Legal term '{term}' not found in simple glossary.",
        "analogy": "Refer to an Indian legal dictionary or consult an advocate for this specific term."
    }

def detect_glossary_terms(text: str) -> list:
    """Find all glossary terms present in a block of text."""
    found = []
    text_lower = text.lower()
    
    for key, data in GLOSSARY.items():
        # Match whole word boundaries where possible
        pattern = r'\b' + re.escape(key) + r'\b'
        if re.search(pattern, text_lower):
            found.append(data)
            
    return found

# Alias for backwards compatibility
extract_jargon = detect_glossary_terms

def get_all_glossary_terms() -> list:
    """Return all glossary terms as a list of dicts."""
    return list(GLOSSARY.values())


